namespace ConEst.Modelos
{
    /// <summary>
    /// Representa un tipo de elemento dentro del sistema, incluyendo su
    /// identificador único y su nombre descriptivo.
    /// </summary>
    public class TiposElementos
    {
        /// <summary>
        /// Identificador único del tipo de elemento.
        /// </summary>
        public int Id { get; set; }

        /// <summary>
        /// Nombre del tipo de elemento.
        /// </summary>
        public string Nombre { get; set; }
    }
}
